import type { DetectiveCase, DetectiveStage, DetectiveChoice } from '../types';

type RoundInput = Omit<DetectiveStage, 'questions' | 'choices'> & {
  questionLabels: [string, string, string, string, string, string, string, string];
  replies: [string, string, string, string, string, string, string, string];
  cards: [string, boolean, string, string[]][];
};

const round = (input: RoundInput): DetectiveStage => ({
  id: input.id,
  title: input.title,
  task: input.task,
  prompt: input.prompt,
  intro: input.intro,
  questions: input.replies.map((reply, index) => ({
    id: `coffee-${input.id}-q${index + 1}`,
    label: input.questionLabels[index],
    reply,
  })),
  choices: input.cards.map(([label, correct, explanation, evidence], index): DetectiveChoice => ({
    id: `coffee-${input.id}-c${String(index + 1).padStart(2, '0')}`,
    label,
    correct,
    explanation,
    evidenceIds: evidence,
    ...(input.id === 'ideas' && [0, 8, 10].includes(index) ? { kind: 'proposal' as const } : {}),
  })),
  terms: input.terms,
  ...(input.aiIdeas ? { aiIdeas: input.aiIdeas } : {}),
});

