// Best-answer positions are balanced; scores reward reasoning, not writing length.
const positions = [2, 0, 3, 1, 2, 0, 1, 3, 2, 1, 3, 0, 2, 1, 3, 0, 2, 1, 0, 3, 1, 2, 0, 3, 2, 0, 3, 1];
const questions: Question[] = [];
function q(id: string, dimension: string, prompt: string, scenario: string,
  ranked: [string, string, string, string], explanation: string, evidence?: { label: string; value: string }[]) {
  const best = positions[questions.length];
  const scores = [0, 1, 2, 3].map((_, i) => (best - i + 3) % 4);
  questions.push({ id, dimension, prompt, scenario, evidence, options: scores.map((score) => ranked[3 - score]), optionScores: scores, correctAnswer: best, explanation });
}
